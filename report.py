"""Report generation.

Part A (build_report) is deterministic: counts and rule-based recommendations
computed from the data. Part B (generate_llm_insights) is OPTIONAL and is shown
separately so LLM text is never mixed with computed statistics.
"""
import os

import requests

from metrics import sentiment_distribution

RECOMMENDATIONS = {
    "Teaching & Faculty": "Run faculty workshops on interactive teaching, share lecture notes in advance, and hold regular doubt-clearing sessions.",
    "Infrastructure": "Audit classrooms, hostels and washrooms, and set up a maintenance schedule with a named owner reviewed monthly.",
    "Laboratories": "Check lab systems and equipment against course needs, repair or replace faulty machines, and add lab slots where practicals are being delayed.",
    "Administration": "Simplify fee, scholarship and document processes, publish clear turnaround times, and offer an online request tracker.",
    "Library": "Review library hours (especially during exams) and update books and digital resources based on student requests.",
    "Internet & Wi-Fi": "Run a Wi-Fi coverage and bandwidth audit for hostels and the library, and upgrade access points in weak areas.",
    "Canteen": "Introduce regular hygiene inspections, publish menu and pricing, and collect canteen feedback every term.",
    "Examinations": "Publish exam schedules and result timelines early, align question papers with the syllabus, and offer a transparent re-evaluation process.",
}
GENERIC_REC = "Read the individual comments for this theme and assign an owner to decide on action."


def _quote(row, limit=150):
    text = row["feedback"]
    if len(text) > limit:
        text = text[:limit].rstrip() + "..."
    return f'"{text}" (score {row["score"]:+.2f})'


def build_report(df, topic_df):
    """Deterministic report. Returns a dict of sections."""
    total = len(df)
    dist = sentiment_distribution(df).set_index("Sentiment")
    pos, neu, neg = (int(dist.loc[s, "Count"]) for s in ("Positive", "Neutral", "Negative"))
    pos_p, neu_p, neg_p = (float(dist.loc[s, "Percent"]) for s in ("Positive", "Neutral", "Negative"))
    avg = float(df["score"].mean())

    gap = pos_p - neg_p
    mood = "mostly positive" if gap >= 20 else "mostly negative" if gap <= -20 else "mixed"
    summary = (
        f"{total} feedback entries were analysed: {pos} positive ({pos_p}%), "
        f"{neu} neutral ({neu_p}%) and {neg} negative ({neg_p}%). "
        f"Overall sentiment is {mood} (average VADER compound score {avg:+.2f})."
    )

    named = topic_df[topic_df["Topic"] != "General"]

    positives = []
    for _, r in named[named["Positive"] > 0].sort_values(["Positive", "Total"], ascending=False).head(3).iterrows():
        positives.append(f"{r['Topic']}: {int(r['Positive'])} of {int(r['Total'])} mentions are positive.")
    for _, r in df[df["sentiment"] == "Positive"].nlargest(3, "score").iterrows():
        positives.append("Example: " + _quote(r))
    if not positives:
        positives = ["No clearly positive feedback was detected."]

    complaints = []
    worst = named[named["Negative"] > 0].sort_values(["Negative", "Negative %"], ascending=False).head(5)
    for _, r in worst.iterrows():
        complaints.append(f"{r['Topic']}: {int(r['Negative'])} of {int(r['Total'])} mentions are negative ({r['Negative %']}%).")
    for _, r in df[df["sentiment"] == "Negative"].nsmallest(3, "score").iterrows():
        complaints.append("Example: " + _quote(r))
    if not complaints:
        complaints = ["No negative feedback was detected."]

    topics = [
        f"{r['Topic']}: {int(r['Total'])} mentions ({int(r['Positive'])} positive / {int(r['Neutral'])} neutral / {int(r['Negative'])} negative)"
        for _, r in named.head(5).iterrows()
    ] or ["No specific themes were detected."]

    recs = []
    needs_action = named[(named["Negative"] >= 2) | ((named["Negative"] >= 1) & (named["Negative %"] >= 50))]
    for _, r in needs_action.sort_values(["Negative", "Negative %"], ascending=False).head(4).iterrows():
        action = RECOMMENDATIONS.get(r["Topic"], GENERIC_REC)
        recs.append(f"{r['Topic']}: {action} (Evidence: {int(r['Negative'])} of {int(r['Total'])} mentions negative.)")
    if not recs:
        recs = ["No theme shows a notable concentration of negative feedback. Keep monitoring and re-run this report as more feedback arrives."]

    caveats = [
        "Sentiment comes from a lexicon-based model (VADER); sarcasm and mixed opinions in one comment can be misjudged.",
        "Topics come from keyword matching, so a comment can be tagged with a theme it only mentions in passing.",
        "Recommendations are rule-based templates matched to the most negative themes; they are not generated by an LLM.",
    ]
    if total < 30:
        caveats.append(f"Only {total} entries were analysed, so percentages can change a lot with a few more comments.")

    return {"summary": summary, "positives": positives, "complaints": complaints,
            "topics": topics, "recommendations": recs, "caveats": caveats}


def report_to_text(report, llm_text=None, generated_at=""):
    lines = ["AI FEEDBACK ANALYZER - REPORT", f"Generated: {generated_at}", "",
             "PART A - COMPUTED FROM THE DATA (statistics + rule-based recommendations)", "",
             "1. OVERALL SUMMARY", report["summary"], ""]
    sections = [("2. KEY POSITIVE FINDINGS", "positives"), ("3. MAJOR COMPLAINTS AND CONCERNS", "complaints"),
                ("4. FREQUENTLY MENTIONED TOPICS", "topics"), ("5. RECOMMENDATIONS", "recommendations"),
                ("NOTES AND LIMITATIONS", "caveats")]
    for title, key in sections:
        lines.append(title)
        lines += [f"- {item}" for item in report[key]]
        lines.append("")
    if llm_text:
        lines += ["PART B - LLM-WRITTEN NARRATIVE (generated by Gemini; verify against Part A)", llm_text]
    return "\n".join(lines)


def build_llm_facts(df, report):
    """Compact fact sheet sent to the LLM (aggregated stats + a few short examples)."""
    def short(series):
        return [t[:200] for t in series.tolist()]
    neg = short(df[df["sentiment"] == "Negative"].nsmallest(5, "score")["feedback"])
    pos = short(df[df["sentiment"] == "Positive"].nlargest(5, "score")["feedback"])
    return "\n".join([
        "SUMMARY: " + report["summary"],
        "TOPICS: " + " | ".join(report["topics"]),
        "COMPLAINT THEMES: " + " | ".join(c for c in report["complaints"] if not c.startswith("Example")),
        "NEGATIVE EXAMPLES: " + " || ".join(neg),
        "POSITIVE EXAMPLES: " + " || ".join(pos),
    ])


def generate_llm_insights(facts, timeout=25):
    """Optional Gemini narrative. Returns (text_or_None, note_or_None). Never raises."""
    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        return None, "No GEMINI_API_KEY configured - showing the statistical report only."
    model = os.getenv("GEMINI_MODEL", "gemini-2.0-flash")
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
    prompt = (
        "You are an education analyst. Using ONLY the data below, write a concise narrative "
        "(about 150 words) and 3 extra suggestions for the institution. Do not invent numbers, "
        "departments or events that are not in the data.\n\n" + facts
    )
    try:
        resp = requests.post(
            url, headers={"x-goog-api-key": api_key, "Content-Type": "application/json"},
            json={"contents": [{"parts": [{"text": prompt}]}]}, timeout=timeout,
        )
        resp.raise_for_status()
        return resp.json()["candidates"][0]["content"]["parts"][0]["text"].strip(), None
    except Exception as exc:  # network error, bad key, wrong model name, blocked response...
        return None, f"LLM unavailable ({type(exc).__name__}) - showing the statistical report only."